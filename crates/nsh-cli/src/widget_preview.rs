//! Local live preview harness for `nsh run --widget [id]` and
//! `nsh dev --widget [id]`.
//!
//! Generates a lightweight NSH preview app inside `.nsh/widget-preview/` that
//! imports the developer's widget TSX entry directly (giving full HMR in < 50ms)
//! and renders Small / Medium / Large widget cards side-by-side with Light,
//! Dark, Tinted, and Desktop Unfocused simulation toggles plus an interactive
//! action / deep-link console.

use std::{
    fs,
    path::{Path, PathBuf},
};

use anyhow::{Context as _, bail};
use nsh_core::widget::WidgetEntryConfig;

/// Prepares `.nsh/widget-preview/<id>.tsx` for `widget_id` (empty string picks
/// the first declared widget in `nsh.json`) and returns the generated entry path.
pub(crate) fn prepare_preview_entry(app_entry: &Path, widget_id: &str) -> anyhow::Result<PathBuf> {
    let entry = dunce::canonicalize(app_entry)?;
    let app_dir = entry
        .parent()
        .context("app entry has no parent directory")?;
    let config = crate::package::read_config(&entry)?;
    if config.widgets.is_empty() {
        bail!(
            "nsh.json declares no \"widgets\": add a widget entry to nsh.json before running with --widget"
        );
    }
    let widget: &WidgetEntryConfig = if widget_id.is_empty() {
        &config.widgets[0]
    } else {
        config
            .widgets
            .iter()
            .find(|w| w.id == widget_id)
            .with_context(|| {
                let names: Vec<&str> = config.widgets.iter().map(|w| w.id.as_str()).collect();
                format!(
                    "widget {widget_id:?} is not declared in nsh.json (available: {})",
                    names.join(", ")
                )
            })?
    };

    // Validate the widget entry statically before opening the preview window.
    crate::check::check_widgets(&entry)?;

    let preview_dir = app_dir.join(".nsh/widget-preview");
    fs::create_dir_all(&preview_dir)?;
    let preview_entry = preview_dir.join(format!("{}.tsx", widget.id));
    // Relative import from `.nsh/widget-preview/<id>.tsx` back to the app root.
    let rel_import = format!("../../{}", widget.entry.trim_start_matches("./"));
    let families_json = serde_json::to_string(
        &widget
            .families
            .iter()
            .map(|f| f.as_str())
            .collect::<Vec<_>>(),
    )?;
    let title = format!("Widget Preview — {} ({})", widget.name, widget.id);

    let tsx = format!(
        r#"// Generated by `nsh run --widget` for local preview with HMR.
import {{ mount, signal, setColorScheme, Text, View, Scroll }} from "nsh";
import {{ Window }} from "nsh/desktop";
import type {{ WidgetFamily, WidgetRenderingMode }} from "nsh/widget";
import widgetDef from {rel_import:?};

const FAMILIES: WidgetFamily[] = {families_json};
const SIZES: Record<WidgetFamily, {{ w: number; h: number; label: string }}> = {{
  small: {{ w: 170, h: 170, label: "Small (170×170)" }},
  medium: {{ w: 364, h: 170, label: "Medium (364×170)" }},
  large: {{ w: 364, h: 382, label: "Large (364×382)" }},
}};

function WidgetPreviewApp() {{
  const appearance = signal<"light" | "dark">("light");
  const mode = signal<WidgetRenderingMode>("fullColor");
  const dataState = signal<"placeholder" | "live" | "empty">("placeholder");
  const data = signal<unknown>(widgetDef.placeholder);
  const logs = signal<string[]>(["Ready — edit {entry_path} to hot-reload."]);

  const appendLog = (line: string) => {{
    const ts = new Date().toLocaleTimeString();
    logs.set([`[${{ts}}] ${{line}}`, ...logs().slice(0, 19)]);
  }};

  const toggleAppearance = (next: "light" | "dark") => {{
    appearance.set(next);
    setColorScheme(next);
  }};

  const effectiveData = () => {{
    if (dataState() === "empty") return undefined;
    return data();
  }};

  const cardFilter = () => {{
    if (mode() === "accented") return "grayscale(1) sepia(0.35) saturate(2.2) hue-rotate(190deg)";
    if (mode() === "vibrant") return "grayscale(0.88) opacity(0.86)";
    return undefined;
  }};

  return (
    <Window title={title:?} width={{920}} height={{680}}>
      <View class="flex-1 flex-col bg-background">
        {{/* Toolbar */}}
        <View class="flex-row items-center justify-between px-4 py-3 border-b border-border bg-card">
          <View class="flex-col">
            <Text class="text-sm font-semibold text-foreground">{widget_name}</Text>
            <Text class="text-xs text-muted-foreground">{widget_id} · {entry_path}</Text>
          </View>
          <View class="flex-row items-center gap-3">
            <View class="flex-row rounded-lg bg-muted p-0.5 gap-0.5">
              {{(["light", "dark"] as const).map((a) => (
                <View
                  class={{appearance() === a ? "px-2.5 py-1 rounded-md bg-card" : "px-2.5 py-1 rounded-md"}}
                  onPress={{() => toggleAppearance(a)}}
                >
                  <Text class="text-xs font-medium text-foreground">{{a === "light" ? "Light" : "Dark"}}</Text>
                </View>
              ))}}
            </View>
            <View class="flex-row rounded-lg bg-muted p-0.5 gap-0.5">
              {{([["fullColor", "Full Color"], ["accented", "Tinted"], ["vibrant", "Unfocused"]] as const).map(([m, label]) => (
                <View
                  class={{mode() === m ? "px-2.5 py-1 rounded-md bg-card" : "px-2.5 py-1 rounded-md"}}
                  onPress={{() => mode.set(m)}}
                >
                  <Text class="text-xs font-medium text-foreground">{{label}}</Text>
                </View>
              ))}}
            </View>
            <View class="flex-row rounded-lg bg-muted p-0.5 gap-0.5">
              {{([["placeholder", "Placeholder"], ["live", "Live"], ["empty", "Empty"]] as const).map(([s, label]) => (
                <View
                  class={{dataState() === s ? "px-2.5 py-1 rounded-md bg-card" : "px-2.5 py-1 rounded-md"}}
                  onPress={{() => dataState.set(s)}}
                >
                  <Text class="text-xs font-medium text-foreground">{{label}}</Text>
                </View>
              ))}}
            </View>
          </View>
        </View>

        {{/* Wallpaper preview stage */}}
        <Scroll class="flex-1" contentClass="p-6 flex-row flex-wrap gap-6 items-start">
          {{FAMILIES.map((family) => {{
            const dim = SIZES[family];
            const renderProps = () => ({{
              data: effectiveData(),
              family,
              isPlaceholder: dataState() === "placeholder",
              date: Date.now(),
            }});
            const rootUrl = () => (typeof widgetDef.url === "function" ? widgetDef.url(renderProps()) : undefined);
            return (
              <View class="flex-col gap-2">
                <View class="flex-row items-center justify-between">
                  <Text class="text-xs font-medium text-muted-foreground">{{dim.label}}</Text>
                  <View
                    class="px-2 py-0.5 rounded bg-secondary"
                    onPress={{() => {{
                      const url = rootUrl();
                      appendLog(url ? `Deep link (${{family}}): ${{url}}` : `No root url() for ${{family}}`);
                    }}}}
                  >
                    <Text class="text-[11px] text-secondary-foreground">Test URL</Text>
                  </View>
                </View>
                <View
                  style={{{{
                    width: dim.w,
                    height: dim.h,
                    borderRadius: 22,
                    overflow: "hidden",
                    filter: cardFilter(),
                  }}}}
                  class="border border-border shadow-lg"
                >
                  {{() => widgetDef.render(renderProps())}}
                </View>
              </View>
            );
          }})}}
        </Scroll>

        {{/* Event & action log */}}
        <View class="h-32 border-t border-border bg-card px-4 py-2 flex-col gap-1">
          <Text class="text-xs font-semibold text-muted-foreground">Preview Console</Text>
          <Scroll class="flex-1">
            {{() => logs().map((line) => (
              <Text class="text-[11px] font-mono text-muted-foreground">{{line}}</Text>
            ))}}
          </Scroll>
        </View>
      </View>
    </Window>
  );
}}

mount(WidgetPreviewApp);
"#,
        entry_path = widget.entry,
        widget_name = widget.name,
        widget_id = widget.id,
    );

    fs::write(&preview_entry, tsx)?;
    Ok(preview_entry)
}
